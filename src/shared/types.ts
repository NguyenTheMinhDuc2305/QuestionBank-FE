export interface QuestionTypeMeta {
  code: QuestionTypeCode;
  nameEn: string; // "Completion-based Selection"
  nameVi: string;
  description: string;
  enabled: boolean; // RESP_SEL = false by default ("Chưa làm trong phase này")
  phaseNote?: string;
  /** Allowed media formats per the sheet */
  questionMedia: Array<"text" | "audio" | "image">;
  answerMedia: Array<"text" | "audio" | "image">;
  /** Path of the JSON Schema the LLM must follow, e.g. "DATA/schemas/ai/COMP_SEL.schema.json" */
  aiSchemaPath: string;
  /** Path of the JSON Schema for the final (post-processed) record, e.g. "DATA/schemas/question/COMP_SEL.schema.json" */
  questionSchemaPath: string;
}

