/** "Key mapping media" — what the CMS uses to search its element store, and what we use to generate media. */
export interface MediaKey {
  id: string; // unique within the run, e.g. "q3_m1"
  kind: MediaKind;
  target: MediaTarget;
  /** For option/pairA/pairB/item targets: the exact text value it illustrates */
  targetValue?: string;
  /** Short search tags for the CMS element store, e.g. ["teacher", "woman", "classroom"] */
  keywords: string[];
  /** Image: visual description of the scene. Audio: the exact text to be spoken. */
  description: string;
  /** Image only: per-image things to avoid (merged with the global policy into ImageAsset.negativePrompt) */
  negativeExtras?: string[];
}

export type AssetStatus = "pending" | "generating" | "done" | "error" | "skipped";

export interface ImageAsset {
  id: string;
  questionId: string;
  mediaKeyId: string;
  /** Final positive prompt sent to the image model */
  prompt: string;
  /** Negative prompt — ALWAYS present (global policy + per-image). Shown in the UI. */
  negativePrompt: string;
  model: string;
  status: AssetStatus;
  /** data: URL (Vercel) or /api/outputs/... path (local) once done */
  url?: string;
  error?: string;
  /** MIME type of the generated file, e.g. "image/png", "image/webp", "audio/wav" */
  mimeType?: string;
  /** Decoded size of the generated file in bytes (for display) */
  bytes?: number;
  /** Local only: /api/outputs/<runId>/<file> path of the saved copy (absent on Vercel) */
  fileUrl?: string;
}

export interface AudioAsset {
  id: string;
  questionId: string;
  mediaKeyId: string;
  text: string; // text to speak
  voice: string;
  model: string; // "browser-tts" when falling back to Web Speech API
  status: AssetStatus;
  url?: string;
  error?: string;
  /** MIME type of the generated file, e.g. "image/png", "image/webp", "audio/wav" */
  mimeType?: string;
  /** Decoded size of the generated file in bytes (for display) */
  bytes?: number;
  /** Local only: /api/outputs/<runId>/<file> path of the saved copy (absent on Vercel) */
  fileUrl?: string;
}

// ---------------------------------------------------------------------------
// Final question records (after CMS-like post-processing). Discriminated by `type`.
// ---------------------------------------------------------------------------

interface QuestionBase {
  id: string; // e.g. "q1"
  type: QuestionTypeCode;
  lo: LORef;
  bloom: BloomLevel;
  hint: string;
  explanation: string;
  mediaKeys: MediaKey[];
  /** Validation warnings from the core logic (e.g. "ORDER has 11 tokens, truncated"). Empty = clean. */
  warnings: string[];
  /** Short normalised text identifying the question (used for de-duplication within and across runs). */
  signature?: string;
  /** The random variation plan the question was written from (angle, character, setting...). For review/debug. */
  variation?: Record<string, string>;
}

export interface CompSelQuestion extends QuestionBase {
  type: "COMP_SEL";
  questionContent: { stem: string }; // contains exactly one "____"
  answerContent: {
    correct: string;
    /** AI returns >= 4 distractors from the same LO-con / unit topic */
    distractorPool: string[];
    /** 4 shuffled options picked by the "CMS" (1 correct + 3 random distractors) */
    options: string[];
  };
  trueAnswer: string;
}

export interface RespSelQuestion extends QuestionBase {
  type: "RESP_SEL";
  questionContent: {
    passage: string; // text paragraph or listening script
    passageMode: "text" | "audio";
    question: string; // complete, meaningful question
  };
  answerContent: { correct: string; distractorPool: string[]; options: string[] };
  trueAnswer: string;
}

export interface TypingQuestion extends QuestionBase {
  type: "TYPING";
  questionContent: { stem: string }; // 100% fill-in-the-blank, exactly one "____"
  answerContent: { answer: string; acceptedVariants: string[] };
  trueAnswer: { answer: string; fullSentence: string }; // "She is a teacher"
}

export interface MatchQuestion extends QuestionBase {
  type: "MATCH";
  questionContent: null;
  answerContent: {
    columnA: string[]; // English words/phrases
    /** en_vi: Vietnamese meanings (text). en_image: the English words again — each rendered as its image
     *  via the mediaKey with target "pairB" and targetValue = that word. Shuffled by the "CMS". */
    columnB: string[];
    /** Optional for backward compatibility with older runs; treat missing as "en_vi". */
    matchMode?: MatchMode;
  };
  trueAnswer: Array<{ a: string; b: string }>;
}

export interface OrderQuestion extends QuestionBase {
  type: "ORDER";
  questionContent: null;
  answerContent: {
    tokens: string[]; // correct order, 2..10 tokens; a token may be a phrase ("a cat")
    tokenString: string; // tokens.join("/space/")
    shuffled: string[]; // display order
  };
  trueAnswer: { sentence: string };
}

export interface ListenQuestion extends QuestionBase {
  type: "LISTEN";
  questionContent: {
    items: Array<{ index: number; sentence: string }>; // "1. This is a black cat"
    audioScript: string; // all items merged into ONE text -> ONE audio
  };
  answerContent: { orderedLabels: string[]; shuffledLabels: string[] }; // labels -> images
  trueAnswer: Array<{ position: number; label: string }>;
}

export interface SpeakQuestion extends QuestionBase {
  type: "SPEAK";
  questionContent: null;
  /** Each value = 1 quiz; each value has its own mediaKey (image + reference audio) */
  answerContent: {
    values: Array<{
      text: string;
      kind: "word" | "phrase" | "sentence";
      mediaKeyIds: string[];
      /** LO cháu code this value practises (SPEAK = one value per selected LO cháu) */
      loCode?: string;
    }>;
  };
  trueAnswer: null;
}

export type GeneratedQuestion =
  | CompSelQuestion
  | RespSelQuestion
  | TypingQuestion
  | MatchQuestion
  | OrderQuestion
  | ListenQuestion
  | SpeakQuestion;

// ---------------------------------------------------------------------------
// API contracts
