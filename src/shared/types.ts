/** "Code AI" column in Structure.csv. RESP_SEL has no code in the sheet (we assign one); it is "Chưa làm trong phase này". */
export type QuestionTypeCode =
  | "COMP_SEL" // Completion-based Selection — fill-in-the-blank, 4 options
  | "RESP_SEL" // Response-based Selection — passage/listening + full question, 4 options (phase 2 / preview)
  | "TYPING" //   Typing — fill-in-the-blank, student types the single answer
  | "MATCH" //    Matching — column A ↔ column B pairs
  | "ORDER" //    Ordering — reorder words/phrases (max 10 tokens, joined by "/space/")
  | "LISTEN" //   Listen - order — audio lists N items, student orders N images
  | "SPEAK"; //   iSpeak — list of words/sentences to pronounce, no true answer

/** Bloom scale from the sheet: M1 nhận biết, M2 thông hiểu, M3 vận dụng, M4 vận dụng cao */
export type BloomLevel = "M1" | "M2" | "M3" | "M4";

export type MediaKind = "image" | "audio";

/** MATCH variants: English ↔ Vietnamese text, or English ↔ image. */
export type MatchMode = "en_vi" | "en_image";

/** Which part of a question a media key attaches to. */
export type MediaTarget =
  | "question" //   the stem / passage / audio script
  | "option" //     one answer option (COMP_SEL / RESP_SEL answer images)
  | "pairA" //      MATCH column A item
  | "pairB" //      MATCH column B item
  | "item" //       LISTEN ordered item (image per item) / SPEAK value
  | "answer"; //    the true answer as a whole

// ---------------------------------------------------------------------------
// Learning objectives (DATA/lo/*.json) — 3 levels: cha (general) > con (specific) > cháu (item)
// ---------------------------------------------------------------------------

export interface LOItem {
  /** LO cháu code, e.g. "AIC_G1_U1_TV1_1" (auto-generated when the source CSV has no code) */
  code: string;
  /** LO cháu content, e.g. "ball" or a grammar pattern block ("Pattern: I have a + [noun]\nConstraint: ...") */
  name: string;
  /** "vocabulary" | "grammar" — from "Phân loại Specific LO" (Từ vựng / Ngữ pháp) */
  category: "vocabulary" | "grammar";
}

export interface LOSpecific {
  code: string; // e.g. "AIC_G1_U1_TV1"
  name: string; // e.g. "Từ vựng chứa âm Bb"
  category: "vocabulary" | "grammar";
  items: LOItem[];
}

export interface LOGeneral {
  code: string; // e.g. "AIC_G1_U1"
  grade: number;
  unit: number;
  nameEn: string; // "In the school playground"
  nameVi: string; // "Ở sân chơi của trường"
  specifics: LOSpecific[];
}

export interface LOTree {
  source: string; // e.g. "DATA/LO-grade6.csv"
  generatedAt: string;
  codesAutoGenerated: boolean;
  generals: LOGeneral[];
}

/** Flattened reference stored on every generated question. */
export interface LORef {
  code: string; // LO cháu code
  name: string; // LO cháu name
  specificCode: string;
  specificName: string;
  generalCode: string;
  generalName: string;
}

// ---------------------------------------------------------------------------
// Question-type catalogue (DATA/schemas/question-types.json)
