/** GET /api/meta */
export interface MetaResponse {
  questionTypes: QuestionTypeMeta[];
  loTree: LOTree;
  bloomLevels: Array<{ code: BloomLevel; nameVi: string; nameEn: string; description: string }>;
  /** maxQuestions = per LO cháu; maxTotalQuestions = per request (count × number of LO). */
  limits: { maxQuestions: number; maxTotalQuestions?: number };
  models: { text: string; image: string; audio: string };
  hasApiKey: boolean;
}

/** POST /api/generate */
export interface GenerateRequest {
  type: QuestionTypeCode;
  loCodes: string[]; // one or more LO cháu codes
  bloom: BloomLevel;
  /** Questions PER selected LO cháu (1..limits.maxQuestions). Total = count × loCodes.length (SPEAK: count quizzes). */
  count: number;
  options?: {
    withImages?: boolean; // default true
    withAudio?: boolean; // default true
    language?: "en"; // content language (English learning)
    /** MATCH only: "auto" lets the model choose per question. Default "auto". */
    matchMode?: "auto" | MatchMode;
    /** Signatures (or texts) of previously generated questions the model must not repeat (max 60). */
    avoid?: string[];
  };
}

export interface GenerateResponse {
  runId: string;
  request: GenerateRequest;
  createdAt: string;
  model: string;
  questions: GeneratedQuestion[];
  /** All image assets with prompt + negativePrompt, status "pending" — the client generates them via /api/media/image */
  images: ImageAsset[];
  audios: AudioAsset[];
  // NOTE: token usage / cost are deliberately NOT part of the API — they are only logged server-side.
  warnings: string[];
}

/** POST /api/media/image */
export interface ImageGenRequest {
  runId: string;
  assetId: string;
  prompt: string;
  negativePrompt: string;
}
export interface ImageGenResponse {
  assetId: string;
  url: string; // always a renderable data: URL (base64 png/jpeg/webp), compressed to stay well under 4.5 MB
  model: string;
  /** MIME type of the generated file, e.g. "image/png", "image/webp", "audio/wav" */
  mimeType?: string;
  /** Decoded size of the generated file in bytes (for display) */
  bytes?: number;
  /** Local only: /api/outputs/<runId>/<file> path of the saved copy (absent on Vercel) */
  fileUrl?: string;
}

/** POST /api/media/audio */
export interface AudioGenRequest {
  runId: string;
  assetId: string;
  text: string;
  voice?: string;
}
export interface AudioGenResponse {
  assetId: string;
  url: string | null; // playable data: URL (audio/wav or audio/mpeg); null => client must fall back to browser speechSynthesis
  model: string;
  /** MIME type of the generated file, e.g. "image/png", "image/webp", "audio/wav" */
  mimeType?: string;
  /** Decoded size of the generated file in bytes (for display) */
  bytes?: number;
  /** Local only: /api/outputs/<runId>/<file> path of the saved copy (absent on Vercel) */
  fileUrl?: string;
  /** Transcript returned by the audio model (should equal the requested text) */
  transcript?: string;
  /** Set when url is null because server TTS failed or is disabled (informational) */
  fallbackReason?: string;
}

export interface ApiError {
  error: string;
  details?: unknown;
}
