export const bloomCode = (level: number): BloomLevel => `M${Math.min(4, Math.max(1, level))}` as BloomLevel;
export const bloomLevel = (code: BloomLevel) => Number(code.slice(1));

/** The UI marks the blank with "____". */
const blank = (s: string) => s.replace(/_{2,}/g, "____");

/** Deterministic shuffle (seeded by the question id) so the display order is stable across renders. */
function shuffle<T>(items: T[], seed: string): T[] {
  let h = 2166136261;
  for (const ch of seed) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0;
    const j = h % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  // Avoid showing the answer key order when the shuffle happens to be the identity.
  if (out.length > 1 && out.every((v, i) => v === items[i])) out.push(out.shift() as T);
  return out;
}

const str = (v: unknown) => (typeof v === "string" ? v : "");
const byNum = (key: string) => (a: Row, b: Row) => Number(a[key]) - Number(b[key]);

function mimeOf(objectKey: string) {
  const ext = objectKey.split(".").pop()?.toLowerCase();
  return (
    { png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp", wav: "audio/wav", mp3: "audio/mpeg" }[ext ?? ""] ??
    undefined
  );
}

export interface Converted {
  question: GeneratedQuestion;
  images: ImageAsset[];
  audios: AudioAsset[];
}

/**
 * Builds one UI question plus its media assets. `lo` supplies the general (unit) name, which the
 * question detail does not include.
 */
export function convertQuestion(w: WorkerQuestion, lo?: WorkerLO): Converted {
  const qid = w.id;
  const mediaKeys: MediaKey[] = [];
  const images: ImageAsset[] = [];
  const audios: AudioAsset[] = [];
  let n = 0;

  /** Registers a media reference for one part of the question (each reference gets its own key). */
  const attach = (mediaId: unknown, target: MediaTarget, targetValue?: string) => {
    const media: WorkerMedia | undefined = typeof mediaId === "string" ? w.media[mediaId] : undefined;
    if (!media) return;
    const keyId = `${qid}:${++n}`;
    const isImage = media.kind === "images";
    mediaKeys.push({
      id: keyId,
      kind: isImage ? "image" : "audio",
      target,
      targetValue,
      keywords: [],
      description: (isImage ? media.prompt : media.transcript) ?? "",
    });
    if (isImage)
      images.push({
        id: `img_${keyId}`,
        questionId: qid,
        mediaKeyId: keyId,
        prompt: media.prompt ?? "",
        negativePrompt: media.negative_prompt ?? "",
        model: media.model_name,
        status: "done",
        url: media.url,
        mimeType: mimeOf(media.object_key),
      });
    else
      audios.push({
        id: `aud_${keyId}`,
        questionId: qid,
        mediaKeyId: keyId,
        text: media.transcript ?? "",
        voice: media.voice ?? "",
        model: media.model_name,
        status: "done",
        url: media.url,
        mimeType: mimeOf(media.object_key),
      });
  };

  const d = (w.detail ?? {}) as Row;
  const base = {
    id: qid,
    lo: loRef(lo ?? { code: w.learning_objectives?.[0]?.code ?? "", content: "", specific_name: "", grade: 1, unit: 0, ...w.learning_objectives?.[0] }),
    bloom: bloomCode(w.bloom_level),
    hint: w.hint,
    explanation: w.explanation,
    mediaKeys,
    warnings: [] as string[],
  };

  let question: GeneratedQuestion;
  switch (w.question_type) {
    case "COMP_SEL": {
      attach(d.image_id, "question");
      attach(d.audio_id, "question");
      const opts = [...w.items].sort(byNum("position"));
      for (const o of opts) {
        attach(o.image_id, "option", str(o.text_content));
        attach(o.audio_id, "option", str(o.text_content));
      }
      const correct = str(opts.find((o) => o.is_correct)?.text_content);
      const texts = opts.map((o) => str(o.text_content));
      question = {
        ...base,
        type: "COMP_SEL",
        questionContent: { stem: blank(str(d.stem_text)) },
        answerContent: { correct, distractorPool: texts.filter((t) => t !== correct), options: shuffle(texts, qid) },
        trueAnswer: correct,
        signature: `${str(d.stem_text)} → ${correct}`,
      };
      break;
    }
    case "TYPING": {
      attach(d.image_id, "question");
      attach(d.audio_id, "question");
      attach(d.answer_audio_id, "answer", str(d.answer_text));
      question = {
        ...base,
        type: "TYPING",
        questionContent: { stem: blank(str(d.stem_text)) },
        answerContent: { answer: str(d.answer_text), acceptedVariants: [] },
        trueAnswer: { answer: str(d.answer_text), fullSentence: str(d.completed_sentence) },
        signature: str(d.completed_sentence),
      };
      break;
    }
    case "MATCH": {
      const pairs = [...w.items].sort(byNum("position"));
      for (const p of pairs) {
        attach(p.left_image_id, "pairA", str(p.left_text));
        attach(p.left_audio_id, "pairA", str(p.left_text));
        attach(p.right_image_id, "pairB", str(p.right_text));
        attach(p.right_audio_id, "pairB", str(p.right_text));
      }
      const withImages = pairs.some((p) => p.right_image_id);
      question = {
        ...base,
        type: "MATCH",
        questionContent: null,
        answerContent: {
          columnA: pairs.map((p) => str(p.left_text)),
          columnB: shuffle(
            pairs.map((p) => str(p.right_text)),
            qid,
          ),
          matchMode: withImages ? "en_image" : "en_vi",
        },
        trueAnswer: pairs.map((p) => ({ a: str(p.left_text), b: str(p.right_text) })),
        signature: pairs.map((p) => `${str(p.left_text)}=${str(p.right_text)}`).join(" | "),
      };
      break;
    }
    case "ORDER": {
      const tokens = [...w.items].sort(byNum("correct_position"));
      for (const t of tokens) attach(t.audio_id, "item", str(t.text_content));
      attach(d.answer_audio_id, "answer", str(d.correct_sentence));
      const words = tokens.map((t) => str(t.text_content));
      question = {
        ...base,
        type: "ORDER",
        questionContent: null,
        answerContent: { tokens: words, tokenString: words.join("/space/"), shuffled: shuffle(words, qid) },
        trueAnswer: { sentence: str(d.correct_sentence) },
        signature: str(d.correct_sentence),
      };
      break;
    }
    case "LISTEN": {
      const items = [...w.items].sort(byNum("correct_position"));
      for (const it of items) {
        attach(it.image_id, "item", str(it.label));
        attach(it.audio_id, "item", str(it.label));
      }
      const labels = items.map((it) => str(it.label));
      const sentences = items.map((it, i) => ({ index: i + 1, sentence: str(it.spoken_text) }));
      const audioScript = sentences.map((s) => `${s.index}. ${s.sentence}`).join(" ");
      // The Worker stores one audio file PER item (in the Audio tab). The question-level player reads
      // the whole script with browser TTS, exactly like the previous POC's fallback.
      const scriptKey = `${qid}:script`;
      mediaKeys.push({ id: scriptKey, kind: "audio", target: "question", keywords: [], description: audioScript });
      audios.push({
        id: `aud_${scriptKey}`,
        questionId: qid,
        mediaKeyId: scriptKey,
        text: audioScript,
        voice: "",
        model: "browser-tts",
        status: "done",
      });
      question = {
        ...base,
        type: "LISTEN",
        questionContent: { items: sentences, audioScript },
        answerContent: { orderedLabels: labels, shuffledLabels: shuffle(labels, qid) },
        trueAnswer: labels.map((label, i) => ({ position: i + 1, label })),
        signature: labels.join(" | "),
      };
      break;
    }
  }
  return { question, images, audios };
}
