/**
 * Converts Worker records (Supabase rows) into the shapes the original QuestionBank UI renders
 * (`@shared/types`), so every existing component is reused unchanged.
 */
import type {
  AudioAsset,
  BloomLevel,
  GeneratedQuestion,
  ImageAsset,
  LOGeneral,
  LORef,
  LOTree,
  MediaKey,
  MediaTarget,
} from "@shared/types";
import type { Row, WorkerLO, WorkerMedia, WorkerQuestion } from "./api-client";

// ---------------------------------------------------------------------------
// Learning objectives
// ---------------------------------------------------------------------------

const isGrammar = (category: string) => /ng[uữ] ?ph[aá]p|grammar/i.test(category);

/** Groups flat LO rows into the 3-level tree used by the LO picker (cha › con › cháu). */
export function buildLoTree(rows: WorkerLO[]): LOTree {
  const generals: LOGeneral[] = [];
  const byGeneral = new Map<string, LOGeneral>();
  const sorted = [...rows].sort((a, b) => a.grade - b.grade || a.unit - b.unit || (a.source_record ?? 0) - (b.source_record ?? 0));
  for (const lo of sorted) {
    const gKey = `G${lo.grade}_U${lo.unit}`;
    let g = byGeneral.get(gKey);
    if (!g) {
      g = { code: gKey, grade: lo.grade, unit: lo.unit, nameEn: lo.general_name, nameVi: "", specifics: [] };
      byGeneral.set(gKey, g);
      generals.push(g);
    }
    const category = isGrammar(lo.category) ? "grammar" : "vocabulary";
    let s = g.specifics.find((x) => x.name === lo.specific_name && x.category === category);
    if (!s) {
      s = { code: `${gKey}_S${g.specifics.length + 1}`, name: lo.specific_name, category, items: [] };
      g.specifics.push(s);
    }
    s.items.push({ code: lo.code, name: lo.content, category });
  }
  return { source: "Supabase learning_objectives", generatedAt: new Date().toISOString(), codesAutoGenerated: true, generals };
}

export function loRef(lo: Pick<WorkerLO, "code" | "content" | "specific_name" | "grade" | "unit"> & { general_name?: string }): LORef {
  return {
    code: lo.code,
    name: lo.content,
    specificCode: lo.specific_name,
    specificName: lo.specific_name,
    generalCode: `G${lo.grade}_U${lo.unit}`,
    generalName: lo.general_name ? `Unit ${lo.unit} · ${lo.general_name}` : `Unit ${lo.unit}`,
  };
}

